impl Default for Background {
    fn default() -> Self {
        Self {
            kind: BackgroundKind::None,
            value: String::new(),
            dim: 35,
            blur: 0,
            terminal: 100,
        }
    }
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub(crate) enum BackgroundKind {
    #[default]
    None,
    Preset,
    Image,
    Mod,
}

impl Background {
    fn clamp(mut self) -> Self {
        self.dim = self.dim.min(95);
        self.blur = self.blur.min(40);
        self.terminal = self.terminal.clamp(30, 100);
        let valid = match self.kind {
            BackgroundKind::None => true,
            BackgroundKind::Preset => BACKGROUND_PRESETS.contains(&self.value.as_str()),
            BackgroundKind::Image => is_image_name(&self.value),
            BackgroundKind::Mod => is_widget_key(&self.value),
        };
        if !valid || self.kind == BackgroundKind::None {
            self.kind = BackgroundKind::None;
            self.value.clear();
        }
        self
    }
}

/// Slots as the page and a hand edit write them, keeping every entry that
/// is a placement and dropping the rest, so one bad entry in a package or a
/// hand-edited settings.json costs that entry rather than the whole file.
fn lenient_slots<'de, D>(deserializer: D) -> Result<BTreeMap<String, Vec<Placement>>, D::Error>
where
    D: serde::Deserializer<'de>,
{
    let raw = Value::deserialize(deserializer)?;
    let mut slots = BTreeMap::new();
    if let Value::Object(map) = raw {
        for (slot, list) in map {
            let Value::Array(entries) = list else {
                continue;
            };
            let placements: Vec<Placement> = entries
                .into_iter()
                .filter_map(|entry| {
                    let widget = entry.get("widget")?.as_str()?.to_owned();
                    let options = match entry.get("options") {
                        Some(Value::Object(options)) => options.clone(),
                        _ => Map::new(),
                    };
                    Some(Placement { widget, options })
                })
                .collect();
            slots.insert(slot, placements);
        }
    }
    Ok(slots)
}

/// A list of strings, keeping the strings and dropping anything else.
fn lenient_strings<'de, D>(deserializer: D) -> Result<Vec<String>, D::Error>
where
    D: serde::Deserializer<'de>,
{
    let raw = Value::deserialize(deserializer)?;
    Ok(match raw {
        Value::Array(entries) => entries
            .into_iter()
            .filter_map(|entry| entry.as_str().map(str::to_owned))
            .collect(),
        _ => Vec::new(),
    })
}

impl Default for Layout {
    fn default() -> Self {
        Self {
            slots: BTreeMap::new(),
            hidden: Vec::new(),
            sizes: BTreeMap::new(),
            files_side: Side::Right,
            rail_side: Side::Left,
            explicit: false,
        }
    }
}

impl Layout {
    fn clamp(mut self) -> Self {
        self.slots.retain(|slot, _| SLOTS.contains(&slot.as_str()));
        for placements in self.slots.values_mut() {
            placements.retain(|placement| is_widget_key(&placement.widget));
            placements.truncate(MAX_PER_SLOT);
        }
        self.slots.retain(|_, placements| !placements.is_empty());
        self.hidden.retain(|key| is_widget_key(key));
        self.hidden.sort();
        self.hidden.dedup();
        self.sizes = self
            .sizes
            .into_iter()
            .filter_map(|(key, value)| {
                PANEL_SIZES
                    .iter()
                    .find(|(name, _, _)| *name == key)
                    .map(|(_, min, max)| (key, value.clamp(*min, *max)))
            })
            .collect();
        self
    }
}

