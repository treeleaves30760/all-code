/// The customisation folder.
#[derive(Debug, Clone)]
pub(crate) struct WebDir {
    root: PathBuf,
}

impl WebDir {
    pub(crate) fn new(config_dir: &Path) -> Self {
        Self {
            root: config_dir.join("web"),
        }
    }

    pub(crate) fn root(&self) -> &Path {
        &self.root
    }

    /// Creates the folder and refreshes the files alc owns in it.
    ///
    /// `AGENTS.md` and `examples/` are alc's, rewritten when they differ, so
    /// an agent always reads the reference for the alc that is running.
    /// Nothing a person wrote - settings, themes, mods - is touched.
    pub(crate) fn scaffold(&self) -> Result<()> {
        for dir in ["mods", "themes", "layouts", "backgrounds"] {
            fs::create_dir_all(self.root.join(dir))
                .with_context(|| format!("failed to create {}", self.root.join(dir).display()))?;
        }
        write_if_changed(&self.root.join("AGENTS.md"), AGENTS_MD)?;
        // 2.8 shipped its examples as `examples/packages/`; they are
        // `examples/layouts/` now, and `examples/` is alc's to tidy.
        let stale = self.root.join("examples").join("packages");
        if fs::symlink_metadata(&stale).is_ok_and(|meta| meta.is_dir()) {
            fs::remove_dir_all(&stale).ok();
        }
        for (relative, contents) in CUSTOM_FILES {
            let path = self.root.join(relative);
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent)?;
            }
            write_if_changed(&path, contents)?;
        }
        Ok(())
    }

    pub(crate) fn load_settings(&self) -> (WebSettings, Option<String>) {
        let path = self.root.join("settings.json");
        match read_capped(&path, MAX_JSON) {
            Ok(None) => (WebSettings::default(), None),
            Ok(Some(text)) => match serde_json::from_str::<WebSettings>(&text) {
                Ok(settings) => (settings.clamp(), None),
                Err(error) => (
                    WebSettings::default(),
                    Some(format!("settings.json: {error}")),
                ),
            },
            Err(error) => (WebSettings::default(), Some(error.to_string())),
        }
    }

    /// Parses, clamps and writes what the page sent; answers with what was
    /// actually saved.
    pub(crate) fn save_settings(&self, body: &[u8]) -> Result<WebSettings> {
        if body.len() as u64 > MAX_JSON {
            bail!("settings are larger than 64 KiB");
        }
        // A file that does not parse is somebody's hand edit, and the page
        // is holding defaults in its place: saving them would erase it.
        if let (_, Some(error)) = self.load_settings() {
            bail!("{error}; fix it (alc remote web check) before saving from the page");
        }
        let settings: WebSettings =
            serde_json::from_slice(body).context("settings are not valid JSON")?;
        let settings = settings.clamp();
        // Measured after indentation (see write_settings): a body under the
        // cap can pretty-print past it.
        self.write_settings(&settings)?;
        Ok(settings)
    }

    /// Turns a mod on or off in settings.json.
    pub(crate) fn set_enabled(&self, id: &str, on: bool) -> Result<()> {
        if !is_slug(id) {
            bail!("`{id}` is not a mod id");
        }
        let (mut settings, error) = self.load_settings();
        if let Some(error) = error {
            bail!("{error}; fix settings.json first (alc remote web check)");
        }
        settings.disabled_mods.retain(|off| off != id);
        if !on {
            settings.disabled_mods.push(id.to_owned());
        }
        self.write_settings(&settings.clamp())
    }

    /// Deletes a mod's folder and forgets its switch and its saved state.
    pub(crate) fn remove_mod(&self, id: &str) -> Result<()> {
        if !is_slug(id) {
            bail!("`{id}` is not a mod id");
        }
        let dir = self.root.join("mods").join(id);
        let is_real_dir = fs::symlink_metadata(&dir)
            .map(|meta| meta.file_type().is_dir())
            .unwrap_or(false);
        if !is_real_dir {
            bail!("there is no mods/{id}");
        }
        fs::remove_dir_all(&dir).with_context(|| format!("could not remove mods/{id}"))?;
        let (mut settings, error) = self.load_settings();
        if error.is_none() {
            settings.disabled_mods.retain(|off| off != id);
            settings.mod_settings.remove(id);
            self.write_settings(&settings)?;
        }
        Ok(())
    }

    fn write_settings(&self, settings: &WebSettings) -> Result<()> {
        fs::create_dir_all(&self.root)?;
        let mut text = serde_json::to_string_pretty(settings)?;
        text.push('\n');
        if text.len() as u64 > MAX_JSON {
            bail!("settings are larger than 64 KiB");
        }
        atomic_write(&self.root.join("settings.json"), text.as_bytes(), false)
    }

    pub(crate) fn snapshot(&self, operator: bool) -> Snapshot {
        // The revision first: a write landing mid-snapshot then yields an
        // old revision with new contents, which the next poll corrects,
        // rather than new revision with old contents, which it never would.
        let revision = self.revision();
        let (settings, settings_error) = self.load_settings();
        let mut mods = self.mods(&settings);
        if settings_error.is_some() {
            for info in &mut mods {
                info.enabled = false;
            }
        }
        Snapshot {
            mods,
            themes: self.themes(),
            revision,
            dir: if operator {
                self.root.display().to_string()
            } else {
                String::new()
            },
            settings,
            settings_error,
            layouts: self.layouts(),
            backgrounds: self.backgrounds(),
            catalog: self.catalog(),
        }
    }

    /// Every mod folder, enabled or not, sorted by id.
    pub(crate) fn mods(&self, settings: &WebSettings) -> Vec<ModInfo> {
        let mut mods = Vec::new();
        for id in slugs(&self.root.join("mods"), true) {
            let dir = self.root.join("mods").join(&id);
            let mut info = ModInfo {
                name: id.clone(),
                enabled: !settings.disabled_mods.contains(&id),
                id,
                description: String::new(),
                version: None,
                author: None,
                has_js: is_plain_file(&dir.join("mod.js")),
                has_css: is_plain_file(&dir.join("mod.css")),
                script_hash: None,
                error: None,
            };
            match read_capped(&dir.join("mod.json"), MAX_JSON) {
                Ok(Some(text)) => match serde_json::from_str::<Manifest>(&text) {
                    Ok(manifest) => {
                        if let Some(name) = manifest.name.filter(|name| !name.trim().is_empty()) {
                            info.name = truncate(name.trim(), 60);
                        }
                        info.description =
                            truncate(manifest.description.unwrap_or_default().trim(), 280);
                        info.version = manifest.version.map(|value| truncate(&value, 24));
                        info.author = manifest.author.map(|value| truncate(&value, 60));
                    }
                    Err(error) => info.error = Some(format!("mod.json: {error}")),
                },
                Ok(None) => {}
                Err(error) => info.error = Some(error.to_string()),
            }
            if !info.has_js && !info.has_css && info.error.is_none() {
                info.error = Some("has neither mod.js nor mod.css".to_owned());
            }
            for (present, file) in [
                (info.has_js, ModFile::Script),
                (info.has_css, ModFile::Style),
            ] {
                if !present || info.error.is_some() {
                    continue;
                }
                match self.mod_file(&info.id, file) {
                    Ok(text) if file == ModFile::Script => info.script_hash = Some(csp_hash(&text)),
                    Ok(_) => {}
                    Err(error) => info.error = Some(error.to_string()),
                }
            }
            mods.push(info);
        }
        mods
    }

    /// One mod file's text. Refuses anything but the fixed names, a symlink,
    /// an oversized file, or bytes that are not UTF-8 - the page hashes the
    /// text it is given, so it has to be exactly the text on disk.
    pub(crate) fn mod_file(&self, id: &str, file: ModFile) -> Result<String> {
        if !is_slug(id) {
            bail!("not a mod id");
        }
        let dir = self.root.join("mods").join(id);
        let is_real_dir = fs::symlink_metadata(&dir)
            .map(|meta| meta.file_type().is_dir())
            .unwrap_or(false);
        if !is_real_dir {
            bail!("no such mod");
        }
        let path = dir.join(file.name());
        match read_capped(&path, MAX_MOD_FILE)? {
            // A browser's UTF-8 decoder drops a leading byte-order mark, so
            // the page would hash different text than this one did.
            Some(text) => Ok(text
                .strip_prefix('\u{feff}')
                .map(str::to_owned)
                .unwrap_or(text)),
            None => bail!("{} is missing", file.name()),
        }
    }

    /// The CSP source for every enabled mod's script, so the page may run
    /// exactly those bytes and nothing else inline.
    pub(crate) fn script_hashes(&self) -> Vec<String> {
        // Fail closed: with settings.json unreadable, which mods are off is
        // unknown, and running one the operator turned off is the worse
        // mistake.
        let (settings, error) = self.load_settings();
        if error.is_some() {
            return Vec::new();
        }
        self.mods(&settings)
            .into_iter()
            .filter(|info| info.enabled && info.error.is_none())
            .filter_map(|info| info.script_hash)
            .collect()
    }

    pub(crate) fn themes(&self) -> Vec<ThemeInfo> {
        let dir = self.root.join("themes");
        let mut themes = Vec::new();
        let Ok(entries) = fs::read_dir(&dir) else {
            return themes;
        };
        let mut names: Vec<String> = entries
            .filter_map(|entry| entry.ok())
            .filter_map(|entry| entry.file_name().into_string().ok())
            .filter_map(|name| name.strip_suffix(".json").map(str::to_owned))
            .filter(|id| is_slug(id))
            .collect();
        names.sort();
        names.truncate(MAX_ENTRIES);
        for id in names {
            let mut theme = ThemeInfo {
                name: id.clone(),
                id: id.clone(),
                mode: "dark".to_owned(),
                tokens: BTreeMap::new(),
                terminal: BTreeMap::new(),
                error: None,
            };
            match read_capped(&dir.join(format!("{id}.json")), MAX_JSON) {
                Ok(Some(text)) => match serde_json::from_str::<ThemeFile>(&text) {
                    Ok(file) => {
                        if let Some(name) = file.name.filter(|name| !name.trim().is_empty()) {
                            theme.name = truncate(name.trim(), 60);
                        }
                        if file.mode.as_deref() == Some("light") {
                            theme.mode = "light".to_owned();
                        }
                        theme.tokens = file
                            .tokens
                            .into_iter()
                            .filter(|(key, value)| is_token_name(key) && is_css_value(value))
                            .collect();
                        theme.terminal = file
                            .terminal
                            .into_iter()
                            .filter(|(key, value)| is_slug(key) && is_css_value(value))
                            .collect();
                    }
                    Err(error) => theme.error = Some(format!("{id}.json: {error}")),
                },
                Ok(None) => continue,
                Err(error) => theme.error = Some(error.to_string()),
            }
            themes.push(theme);
        }
        themes
    }

    /// A short fingerprint of every file the page reads from the folder.
    pub(crate) fn revision(&self) -> String {
        let mut hasher = Sha256::new();
        let mut visit = |path: &Path| {
            if let Ok(meta) = fs::symlink_metadata(path) {
                hasher.update(path.to_string_lossy().as_bytes());
                hasher.update(meta.len().to_le_bytes());
                let modified = meta
                    .modified()
                    .ok()
                    .and_then(|time| time.duration_since(UNIX_EPOCH).ok())
                    .map(|time| time.as_nanos())
                    .unwrap_or_default();
                hasher.update(modified.to_le_bytes());
            }
        };
        visit(&self.root.join("settings.json"));
        for id in slugs(&self.root.join("mods"), true) {
            for file in ["mod.json", "mod.js", "mod.css"] {
                visit(&self.root.join("mods").join(&id).join(file));
            }
        }
        for dir in ["themes", "layouts", "packages", "backgrounds"] {
            if let Ok(entries) = fs::read_dir(self.root.join(dir)) {
                let mut paths: Vec<PathBuf> =
                    entries.filter_map(|e| e.ok()).map(|e| e.path()).collect();
                paths.sort();
                for path in paths.iter().take(MAX_ENTRIES) {
                    visit(path);
                }
            }
        }
        let digest = hasher.finalize();
        digest[..8]
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect()
    }

    /// Every layout in `layouts/` and the 2.8 `packages/`, one entry per
    /// id (`layouts/` wins), sorted by id.
    pub(crate) fn layouts(&self) -> Vec<LayoutInfo> {
        let mut ids: Vec<String> = LAYOUT_DIRS
            .iter()
            .flat_map(|dir| json_ids(&self.root.join(dir)))
            .collect();
        ids.sort();
        ids.dedup();
        ids.truncate(MAX_ENTRIES);
        ids.into_iter()
            .map(|id| {
                let legacy = self
                    .layout_path(&id)
                    .is_some_and(|(dir, _)| dir == "packages");
                match self.load_layout(&id) {
                    Ok(def) => LayoutInfo {
                        id,
                        def,
                        legacy,
                        error: None,
                    },
                    Err(error) => LayoutInfo {
                        def: LayoutDef {
                            name: id.clone(),
                            ..LayoutDef::default()
                        },
                        id,
                        legacy,
                        error: Some(format!("{error:#}")),
                    },
                }
            })
            .collect()
    }

    /// Which folder holds layout `id`, and the file.
    fn layout_path(&self, id: &str) -> Option<(&'static str, PathBuf)> {
        LAYOUT_DIRS.iter().find_map(|dir| {
            let path = self.root.join(dir).join(format!("{id}.json"));
            is_plain_file(&path).then_some((*dir, path))
        })
    }

    pub(crate) fn load_layout(&self, id: &str) -> Result<LayoutDef> {
        if !is_slug(id) {
            bail!("`{id}` is not a layout id");
        }
        let Some((dir, path)) = self.layout_path(id) else {
            bail!("there is no layouts/{id}.json");
        };
        let Some(text) = read_capped(&path, MAX_JSON)? else {
            bail!("there is no {dir}/{id}.json");
        };
        let def: LayoutDef =
            serde_json::from_str(&text).with_context(|| format!("{dir}/{id}.json"))?;
        Ok(def.clamp(id))
    }

    /// Writes a layout the page (or a person) put together. Always to
    /// `layouts/`, where it then wins over a `packages/` file of that id.
    pub(crate) fn save_layout(&self, id: &str, body: &[u8]) -> Result<LayoutDef> {
        if !is_slug(id) {
            bail!("`{id}` is not a layout id ([a-z0-9_-], up to 48)");
        }
        if body.len() as u64 > MAX_JSON {
            bail!("a layout is at most 64 KiB");
        }
        let def: LayoutDef = serde_json::from_slice(body).context("not a layout")?;
        let def = def.clamp(id);
        let mut text = serde_json::to_string_pretty(&def)?;
        text.push('\n');
        fs::create_dir_all(self.root.join("layouts"))?;
        atomic_write(
            &self.root.join("layouts").join(format!("{id}.json")),
            text.as_bytes(),
            false,
        )?;
        Ok(def)
    }

    /// Deletes layout `id` from whichever folders hold it. Removing the
    /// active one first goes back to Default, so its mods do not linger.
    pub(crate) fn remove_layout(&self, id: &str) -> Result<()> {
        if !is_slug(id) {
            bail!("`{id}` is not a layout id");
        }
        let paths: Vec<PathBuf> = LAYOUT_DIRS
            .iter()
            .map(|dir| self.root.join(dir).join(format!("{id}.json")))
            .filter(|path| is_plain_file(path))
            .collect();
        if paths.is_empty() {
            bail!("there is no layouts/{id}.json");
        }
        let (settings, error) = self.load_settings();
        if error.is_none() && settings.active_layout.as_deref() == Some(id) {
            self.reset_layout()?;
        }
        for path in paths {
            fs::remove_file(&path)
                .with_context(|| format!("could not remove {}", path.display()))?;
        }
        Ok(())
    }

    /// Makes a layout the page's.
    ///
    /// 1. Mods the previous layout switched on that this one does not name
    ///    go off again.
    /// 2. Its mods go on (official ones it needs are installed); the ones
    ///    that were off are remembered in `layoutMods`.
    /// 3. It takes the theme, accent, density, widget layout, background and
    ///    terminal font, and becomes `activeLayout`.
    ///
    /// A mod it names that came from elsewhere and is off is code nobody has
    /// switched on yet. Unless `enable_mods` says the person read it, the
    /// layout is not applied at all and `review` lists them: half a skin -
    /// the theme without the CSS that makes it readable - is worse than none.
    pub(crate) fn apply_layout(&self, id: &str, enable_mods: bool) -> Result<Applied> {
        let def = self.load_layout(id)?;
        let (mut settings, error) = self.load_settings();
        if let Some(error) = error {
            bail!("{error}; fix settings.json first (alc remote web check)");
        }
        let mut applied = Applied::default();
        let mut to_install = Vec::new();
        for mod_id in &def.mods {
            if self.root.join("mods").join(mod_id).is_dir() {
                let off = settings.disabled_mods.iter().any(|off| off == mod_id);
                if off && !self.is_trusted_mod(mod_id) {
                    applied.review.push(ReviewMod {
                        id: mod_id.clone(),
                        source: self.mod_source(mod_id),
                    });
                }
            } else if self.catalog_has(CatalogKind::Mod, mod_id) {
                to_install.push(mod_id.clone());
            } else {
                applied.missing.push(mod_id.clone());
            }
        }
        if !applied.review.is_empty() && !enable_mods {
            applied.settings = settings;
            return Ok(applied);
        }
        let before = self.running_scripts(&settings);
        // What the previous layout switched on and this one does not want.
        let mut layout_mods: Vec<String> = Vec::new();
        for mod_id in std::mem::take(&mut settings.layout_mods) {
            if def.mods.contains(&mod_id) {
                layout_mods.push(mod_id);
            } else if self.root.join("mods").join(&mod_id).is_dir()
                && !settings.disabled_mods.contains(&mod_id)
            {
                settings.disabled_mods.push(mod_id);
            }
        }
        for mod_id in &to_install {
            self.install_official(CatalogKind::Mod, mod_id, false)?;
            applied.installed.push(mod_id.clone());
            settings.disabled_mods.retain(|off| off != mod_id);
            layout_mods.push(mod_id.clone());
        }
        for mod_id in &def.mods {
            if applied.missing.contains(mod_id) {
                continue;
            }
            if settings.disabled_mods.iter().any(|off| off == mod_id) {
                settings.disabled_mods.retain(|off| off != mod_id);
                layout_mods.push(mod_id.clone());
            }
        }
        settings.layout_mods = layout_mods;
        // The person's own look, kept once, from before any layout.
        if settings.active_layout.is_none() || settings.layout_restore.is_none() {
            settings.layout_restore = Some(LookRestore {
                theme: settings.theme.clone(),
                accent: settings.accent.clone(),
                density: settings.density,
            });
        }
        let restore = settings.layout_restore.clone();
        match &def.theme {
            Some(theme) => {
                if !self.is_known_theme(theme) && self.catalog_has(CatalogKind::Theme, theme) {
                    self.install_official(CatalogKind::Theme, theme, false)?;
                }
                settings.theme = theme.clone();
            }
            None => {
                if let Some(restore) = &restore {
                    settings.theme = restore.theme.clone();
                }
            }
        }
        settings.accent = match (&def.accent, &def.theme) {
            (Some(accent), _) => Some(accent.clone()),
            // A theme of its own brings its own accent.
            (None, Some(_)) => None,
            (None, None) => restore.as_ref().and_then(|restore| restore.accent.clone()),
        };
        settings.density = def
            .density
            .or(restore.as_ref().map(|restore| restore.density))
            .unwrap_or(settings.density);
        settings.layout = def.layout.clone().unwrap_or_default();
        settings.layout.explicit = true;
        settings.background = def.background.clone().unwrap_or_default();
        settings.layout_terminal = def.terminal.clone();
        settings.active_layout = Some(id.to_owned());
        let settings = settings.clamp();
        self.write_settings(&settings)?;
        // Off counts as much as on: a script that stopped being wanted is
        // still running in every open page until it reloads.
        applied.reload = self.running_scripts(&settings) != before;
        applied.applied = true;
        applied.settings = settings;
        Ok(applied)
    }

    /// Default: no layout. Switches off what layouts switched on, gives the
    /// person their own theme, accent and density back, and puts the
    /// widgets, background and terminal back to alc's own.
    pub(crate) fn reset_layout(&self) -> Result<Applied> {
        let (mut settings, error) = self.load_settings();
        if let Some(error) = error {
            bail!("{error}; fix settings.json first (alc remote web check)");
        }
        let before = self.running_scripts(&settings);
        for mod_id in std::mem::take(&mut settings.layout_mods) {
            if self.root.join("mods").join(&mod_id).is_dir()
                && !settings.disabled_mods.contains(&mod_id)
            {
                settings.disabled_mods.push(mod_id);
            }
        }
        if let Some(restore) = settings.layout_restore.take() {
            settings.theme = restore.theme;
            settings.accent = restore.accent;
            settings.density = restore.density;
        }
        settings.active_layout = None;
        settings.layout_terminal = None;
        settings.layout = Layout::default();
        settings.background = Background::default();
        let settings = settings.clamp();
        self.write_settings(&settings)?;
        Ok(Applied {
            applied: true,
            reload: self.running_scripts(&settings) != before,
            settings,
            ..Applied::default()
        })
    }

    /// The ids of enabled mods with a script.
    fn running_scripts(&self, settings: &WebSettings) -> Vec<String> {
        self.mods(settings)
            .into_iter()
            .filter(|info| info.enabled && info.has_js)
            .map(|info| info.id)
            .collect()
    }

    /// Where a mod was installed from, as its `SOURCE` file says.
    fn mod_source(&self, id: &str) -> String {
        fs::read_to_string(self.root.join("mods").join(id).join("SOURCE"))
            .map(|text| truncate(text.trim(), 200))
            .unwrap_or_default()
    }

    /// A mod alc shipped, or one written here (no SOURCE file): nothing a
    /// person has not had the chance to read before it runs.
    fn is_trusted_mod(&self, id: &str) -> bool {
        match fs::read_to_string(self.root.join("mods").join(id).join("SOURCE")) {
            Ok(source) => source.trim() == "alc (official)",
            Err(_) => true,
        }
    }

    fn is_known_theme(&self, theme: &str) -> bool {
        BUILT_IN_THEMES.contains(&theme)
            || self
                .root
                .join("themes")
                .join(format!("{theme}.json"))
                .is_file()
    }

    /// The official mods, layouts and themes alc ships, and the templates
    /// a new mod starts from.
    pub(crate) fn catalog(&self) -> Catalog {
        let mut catalog = Catalog::default();
        for (path, text) in CUSTOM_FILES {
            let parts: Vec<&str> = path.split('/').collect();
            match parts.as_slice() {
                ["examples", "mods", id, "mod.json"] => {
                    let manifest: Manifest = serde_json::from_str(text).unwrap_or_default();
                    catalog.mods.push(CatalogEntry {
                        id: (*id).to_owned(),
                        name: manifest.name.unwrap_or_else(|| (*id).to_owned()),
                        description: manifest.description.unwrap_or_default(),
                        installed: self.root.join("mods").join(id).is_dir(),
                        layout: None,
                    });
                }
                ["examples", "templates", id, "mod.json"] => {
                    let manifest: Manifest = serde_json::from_str(text).unwrap_or_default();
                    catalog.templates.push(CatalogEntry {
                        id: (*id).to_owned(),
                        name: manifest.name.unwrap_or_else(|| (*id).to_owned()),
                        description: manifest.description.unwrap_or_default(),
                        installed: false,
                        layout: None,
                    });
                }
                ["examples", "layouts", file] => {
                    if let Some(id) = file.strip_suffix(".json") {
                        let def: LayoutDef = serde_json::from_str(text).unwrap_or_default();
                        let def = def.clamp(id);
                        catalog.layouts.push(CatalogEntry {
                            id: id.to_owned(),
                            name: def.name.clone(),
                            description: def.description.clone(),
                            installed: self.layout_path(id).is_some(),
                            layout: Some(def),
                        });
                    }
                }
                ["examples", "themes", file] => {
                    if let Some(id) = file.strip_suffix(".json") {
                        let theme: ThemeFile = serde_json::from_str(text).unwrap_or_default();
                        catalog.themes.push(CatalogEntry {
                            id: id.to_owned(),
                            name: theme.name.unwrap_or_else(|| id.to_owned()),
                            description: String::new(),
                            installed: self
                                .root
                                .join("themes")
                                .join(format!("{id}.json"))
                                .is_file(),
                            layout: None,
                        });
                    }
                }
                _ => {}
            }
        }
        catalog
    }

    fn catalog_has(&self, kind: CatalogKind, id: &str) -> bool {
        let catalog = self.catalog();
        let list = match kind {
            CatalogKind::Mod => &catalog.mods,
            CatalogKind::Layout => &catalog.layouts,
            CatalogKind::Theme => &catalog.themes,
        };
        list.iter().any(|entry| entry.id == id)
    }

    /// Copies an official mod, layout or theme into the folder. A mod
    /// arrives on - it is alc's own code, the same trust as the page - and
    /// replaces an installed copy only with `force`.
    pub(crate) fn install_official(&self, kind: CatalogKind, id: &str, force: bool) -> Result<()> {
        if !is_slug(id) {
            bail!("`{id}` is not an id");
        }
        let (prefix, target): (String, PathBuf) = match kind {
            CatalogKind::Mod => (
                format!("examples/mods/{id}/"),
                self.root.join("mods").join(id),
            ),
            CatalogKind::Layout => (
                format!("examples/layouts/{id}.json"),
                self.root.join("layouts").join(format!("{id}.json")),
            ),
            CatalogKind::Theme => (
                format!("examples/themes/{id}.json"),
                self.root.join("themes").join(format!("{id}.json")),
            ),
        };
        let files: Vec<&(&str, &str)> = CUSTOM_FILES
            .iter()
            .filter(|(path, _)| path.starts_with(&prefix) || *path == prefix)
            .collect();
        if files.is_empty() {
            bail!("alc ships no {kind:?} named `{id}`", kind = kind);
        }
        if target.exists() && !force {
            bail!("{} already exists", target.display());
        }
        match kind {
            CatalogKind::Mod => {
                if target.exists() {
                    fs::remove_dir_all(&target)?;
                }
                fs::create_dir_all(&target)?;
                for (path, text) in files {
                    let name = &path[prefix.len()..];
                    atomic_write(&target.join(name), text.as_bytes(), false)?;
                }
                fs::write(target.join("SOURCE"), "alc (official)\n")?;
                let (settings, error) = self.load_settings();
                if error.is_none() && settings.disabled_mods.iter().any(|off| off == id) {
                    self.set_enabled(id, true)?;
                }
            }
            CatalogKind::Layout | CatalogKind::Theme => {
                if let Some(parent) = target.parent() {
                    fs::create_dir_all(parent)?;
                }
                atomic_write(&target, files[0].1.as_bytes(), false)?;
            }
        }
        Ok(())
    }

    /// Starts a mod from one of the templates, with its id and name filled
    /// in. The mod arrives on: a person made it on purpose.
    pub(crate) fn create_mod(&self, id: &str, template: &str, name: Option<&str>) -> Result<()> {
        if !is_slug(id) {
            bail!("`{id}` is not a mod id ([a-z0-9_-], up to 48)");
        }
        if !is_slug(template) {
            bail!("`{template}` is not a template");
        }
        let dir = self.root.join("mods").join(id);
        if dir.exists() {
            bail!("mods/{id} already exists");
        }
        let prefix = format!("examples/templates/{template}/");
        let files: Vec<&(&str, &str)> = CUSTOM_FILES
            .iter()
            .filter(|(path, _)| path.starts_with(&prefix))
            .collect();
        if files.is_empty() {
            bail!("there is no template `{template}`");
        }
        let name = name
            .map(str::trim)
            .filter(|name| !name.is_empty())
            .map(|name| truncate(name, 60))
            .unwrap_or_else(|| id.to_owned());
        // Quoted so a name cannot break out of the JSON or JS string it is
        // put in; the quotes themselves come off.
        let quoted = serde_json::to_string(&name)?;
        let bare = &quoted[1..quoted.len() - 1];
        fs::create_dir_all(&dir)?;
        for (path, text) in files {
            let file = &path[prefix.len()..];
            let text = text.replace("__MOD_ID__", id).replace("__MOD_NAME__", bare);
            atomic_write(&dir.join(file), text.as_bytes(), false)?;
        }
        Ok(())
    }

    /// The images in `backgrounds/`.
    pub(crate) fn backgrounds(&self) -> Vec<BackgroundImage> {
        let Ok(entries) = fs::read_dir(self.root.join("backgrounds")) else {
            return Vec::new();
        };
        let mut images: Vec<BackgroundImage> = entries
            .filter_map(|entry| entry.ok())
            .filter(|entry| entry.file_type().is_ok_and(|kind| kind.is_file()))
            .filter_map(|entry| {
                let name = entry.file_name().into_string().ok()?;
                let size = entry.metadata().ok()?.len();
                is_image_name(&name).then_some(BackgroundImage { name, size })
            })
            .collect();
        images.sort_by(|a, b| a.name.cmp(&b.name));
        images.truncate(MAX_ENTRIES);
        images
    }

    /// One background image's bytes and content type.
    pub(crate) fn read_background(&self, name: &str) -> Result<(Vec<u8>, &'static str)> {
        let Some(kind) = image_type(name).filter(|_| is_image_name(name)) else {
            bail!("not an image name");
        };
        let path = self.root.join("backgrounds").join(name);
        let meta = fs::symlink_metadata(&path).context("no such image")?;
        if !meta.file_type().is_file() {
            bail!("not a plain file");
        }
        if meta.len() > MAX_IMAGE {
            bail!("larger than {} MiB", MAX_IMAGE / 1024 / 1024);
        }
        Ok((fs::read(&path)?, kind))
    }

    pub(crate) fn save_background(&self, name: &str, bytes: &[u8]) -> Result<()> {
        if !is_image_name(name) {
            bail!("an image is named like `sky.png` ([a-z0-9_-] and png, jpg, jpeg, webp or gif)");
        }
        if bytes.len() as u64 > MAX_IMAGE {
            bail!("larger than {} MiB", MAX_IMAGE / 1024 / 1024);
        }
        if !looks_like_image(bytes) {
            bail!("that is not a PNG, JPEG, WebP or GIF");
        }
        fs::create_dir_all(self.root.join("backgrounds"))?;
        atomic_write(&self.root.join("backgrounds").join(name), bytes, false)
    }

    pub(crate) fn remove_background(&self, name: &str) -> Result<()> {
        if !is_image_name(name) {
            bail!("not an image name");
        }
        let path = self.root.join("backgrounds").join(name);
        if !is_plain_file(&path) {
            bail!("there is no backgrounds/{name}");
        }
        fs::remove_file(path)?;
        Ok(())
    }

    /// Everything `alc remote web check` reports: one line per problem.
    pub(crate) fn check(&self) -> Vec<String> {
        let mut problems = Vec::new();
        let (settings, settings_error) = self.load_settings();
        problems.extend(settings_error);
        let mods = self.mods(&settings);
        for info in &mods {
            if let Some(error) = &info.error {
                problems.push(format!("mods/{}: {error}", info.id));
            }
        }
        for id in &settings.disabled_mods {
            if !mods.iter().any(|info| &info.id == id) {
                problems.push(format!(
                    "settings.json: disabledMods names `{id}`, which is not in mods/"
                ));
            }
        }
        for theme in self.themes() {
            if let Some(error) = theme.error {
                problems.push(format!("themes/{error}"));
            }
        }
        let layouts = self.layouts();
        for info in &layouts {
            if let Some(error) = &info.error {
                let dir = if info.legacy { "packages" } else { "layouts" };
                problems.push(format!("{dir}/{}.json: {error}", info.id));
            }
        }
        if let Some(active) = &settings.active_layout
            && !layouts.iter().any(|info| &info.id == active)
        {
            problems.push(format!(
                "settings.json: activeLayout `{active}` is in neither layouts/ nor packages/"
            ));
        }
        if settings.background.kind == BackgroundKind::Image
            && !self
                .root
                .join("backgrounds")
                .join(&settings.background.value)
                .is_file()
        {
            problems.push(format!(
                "settings.json: background image `{}` is not in backgrounds/",
                settings.background.value
            ));
        }
        let theme = settings.theme.as_str();
        if !self.is_known_theme(theme) {
            problems.push(format!(
                "settings.json: theme `{theme}` is neither built in nor in themes/"
            ));
        }
        problems
    }
}

